/**
 * Helper to fetch a nested translation string with safe fallback.
 * Example: t('hi', 'nav.home') => 'होम'
 */
export const t = (langCode, keyPath, fallback = '') => {
  const lang = translations[langCode] || translations.en;
  const parts = keyPath.split('.');
  let curr = lang;
  for (const p of parts) {
    if (curr && curr[p] !== undefined) {
      curr = curr[p];
    } else {
      // Fallback to English if missing in chosen language
      let enCurr = translations.en;
      for (const ep of parts) {
        if (enCurr && enCurr[ep] !== undefined) {
          enCurr = enCurr[ep];
        } else {
          return fallback || keyPath;
        }
      }
      return enCurr || fallback || keyPath;
    }
  }
  return curr !== undefined ? curr : (fallback || keyPath);
};
